import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const sourceUrl =
  'https://gitlab.com/ClearURLs/rules/-/raw/master/data.min.json';
const outputPath = resolve('src/utils/url/tracker/clearurls.generated.ts');

const response = await fetch(sourceUrl);
if (!response.ok) {
  throw new Error(
    `Failed to fetch ClearURLs rules: ${response.status} ${response.statusText}`,
  );
}

const data = await response.json();
const providers = Object.entries(data.providers ?? {})
  .map(([name, provider]) => ({
    name,
    urlPattern: provider.urlPattern,
    rules: [...(provider.rules ?? []), ...(provider.referralMarketing ?? [])],
    rawRules: provider.rawRules ?? [],
    exceptions: provider.exceptions ?? [],
  }))
  .filter(
    (provider) =>
      provider.urlPattern &&
      provider.rules.length + provider.rawRules.length > 0,
  );

const globalProvider = data.providers?.globalRules;
const globalRules = JSON.stringify(
  [
    ...(globalProvider?.rules ?? []),
    ...(globalProvider?.referralMarketing ?? []),
  ],
  null,
  2,
);
const providerRules = JSON.stringify(providers, null, 2);
const output = [
  '// Generated by scripts/convert-clearurls-rules.mjs. Do not edit manually.',
  '/* eslint-disable @stylistic/quote-props */',
  '',
  'export interface ClearUrlsProviderRules {',
  '  name: string;',
  '  urlPattern: string;',
  '  rules: string[];',
  '  rawRules: string[];',
  '  exceptions: string[];',
  '}',
  '',
  `export const CLEARURLS_GLOBAL_RULES = ${globalRules} as const;`,
  '',
  `export const CLEARURLS_PROVIDERS: ClearUrlsProviderRules[] = ${providerRules};`,
  '',
].join('\n');

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, 'utf8');
console.log(
  `Converted ${providers.length} ClearURLs providers to ${outputPath}`,
);
